// ============================================================
//  timebase.h — จัดการเวลา NTP และการสร้าง key
//
//  ทำไมต้องมีโมดูลนี้:
//  เวอร์ชันเดิมใช้ millis() เป็น key พอบอร์ด reboot ค่าจะย้อนกลับ
//  ไปเริ่มที่ 0 ทำให้ query ?orderBy="$key"&limitToLast ฝั่ง dashboard
//  ดึงแต่ข้อมูลชุดเก่าก่อน reboot ตลอดกาล → หน้าจอค้าง
//  แก้ด้วยการใช้ epoch time จาก NTP ซึ่งโตขึ้นเรื่อย ๆ ข้าม reboot
// ============================================================
#pragma once
#include <Arduino.h>

// sync เวลากับ NTP — คืน false ถ้าไม่สำเร็จภายใน NTP_TIMEOUT_MS
bool timebaseBegin();

// เวลา epoch UTC หน่วยมิลลิวินาที
uint64_t epochMillis();

// ปัดเวลาให้เป็นทวีคูณของ KEY_STEP_MS (20 ms)
//
// ⚠️ สำคัญมาก: ถ้าไม่ปัด key จะเป็นเลขเวลาจริงเช่น ...400123
// ซึ่ง cleanup ที่ไล่เดา key ทีละ 20 ms จะไม่มีทางเดาตรงสักตัว
// → ลบข้อมูลเก่าไม่ได้เลย → ฐานข้อมูลโตไม่หยุด
uint64_t quantize(uint64_t ms);

// แปลงเป็น key ความยาวคงที่ 13 หลัก (zero-padded)
// ความยาวเท่ากันเสมอ → เรียงลำดับถูกทั้งแบบตัวเลขและตัวอักษร
String keyOf(uint64_t ms);
